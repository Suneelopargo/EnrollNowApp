-- EnrollNow
-- V16: Transactional Outbox
--
-- Reliable event foundation for downstream processing.
--
-- IMPORTANT:
-- Business-table changes and insertion into outbox_events
-- should occur inside the SAME database transaction.
--
-- A background worker/process can later publish or project
-- these events to reporting, integrations, notifications, etc.
--
-- All records remain tenant-scoped.

SET search_path TO enrollnow, public;


-- ============================================================
-- OUTBOX EVENTS
-- ============================================================

CREATE TABLE outbox_events (
    id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id               UUID NOT NULL,

    /*
     * Aggregate/entity that caused the event.
     *
     * Examples:
     * PARTICIPANT
     * STUDY_CANDIDATE
     * CONSENT
     * STUDY_ENROLLMENT
     * TASK
     * COMMUNICATION
     */
    aggregate_type          VARCHAR(100) NOT NULL,

    aggregate_id            UUID NOT NULL,

    /*
     * Examples:
     * PARTICIPANT_CREATED
     * PARTICIPANT_UPDATED
     * CANDIDATE_QUALIFIED
     * CONSENT_RECORDED
     * PARTICIPANT_ENROLLED
     * TASK_COMPLETED
     */
    event_type              VARCHAR(150) NOT NULL,

    /*
     * Version allows consumers to evolve event contracts.
     */
    event_version           INTEGER NOT NULL DEFAULT 1,

    /*
     * Event payload.
     *
     * JSONB is intentional because different event types
     * legitimately have different structures.
     */
    payload                 JSONB NOT NULL,

    /*
     * Optional metadata such as:
     * actorUserId
     * source
     * requestId
     * originatingService
     */
    metadata                JSONB NOT NULL DEFAULT '{}'::jsonb,

    /*
     * Correlates multiple events generated by one workflow/request.
     */
    correlation_id          UUID,

    /*
     * Optional causation relationship.
     *
     * Example:
     * Event B was caused by Event A.
     */
    causation_id            UUID,

    /*
     * Idempotency key for consumers / event creation.
     * Optional because not all event producers may supply one.
     */
    idempotency_key         VARCHAR(255),

    status                  VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    available_at            TIMESTAMPTZ NOT NULL DEFAULT now(),

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    locked_at               TIMESTAMPTZ,
    locked_by               VARCHAR(255),

    published_at            TIMESTAMPTZ,

    failed_at               TIMESTAMPTZ,

    retry_count             INTEGER NOT NULL DEFAULT 0,

    last_error              TEXT,

    CONSTRAINT fk_outbox_events_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants(id),

    CONSTRAINT uk_outbox_events_tenant_id
        UNIQUE (tenant_id, id),

    CONSTRAINT ck_outbox_events_version
        CHECK (event_version > 0),

    CONSTRAINT ck_outbox_events_retry_count
        CHECK (retry_count >= 0),

    CONSTRAINT ck_outbox_events_status
        CHECK (
            status IN (
                'PENDING',
                'PROCESSING',
                'PUBLISHED',
                'FAILED',
                'DEAD_LETTER'
            )
        )
);


CREATE INDEX ix_outbox_events_pending
    ON outbox_events (
        status,
        available_at,
        created_at
    )
    WHERE status IN ('PENDING', 'FAILED');


CREATE INDEX ix_outbox_events_tenant_pending
    ON outbox_events (
        tenant_id,
        status,
        available_at,
        created_at
    );


CREATE INDEX ix_outbox_events_aggregate
    ON outbox_events (
        tenant_id,
        aggregate_type,
        aggregate_id,
        created_at
    );


CREATE INDEX ix_outbox_events_type
    ON outbox_events (
        tenant_id,
        event_type,
        created_at
    );


CREATE INDEX ix_outbox_events_correlation
    ON outbox_events (
        tenant_id,
        correlation_id
    );


CREATE UNIQUE INDEX uk_outbox_events_idempotency
    ON outbox_events (
        tenant_id,
        idempotency_key
    )
    WHERE idempotency_key IS NOT NULL;


-- ============================================================
-- OUTBOX EVENT ATTEMPTS
--
-- Append-only processing-attempt history.
--
-- This allows us to understand:
--   when processing was attempted
--   which processor handled it
--   whether it succeeded
--   what error occurred
--
-- The current retry_count is also maintained on outbox_events
-- for efficient worker queries.
-- ============================================================

CREATE TABLE outbox_event_attempts (
    id                      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id               UUID NOT NULL,

    outbox_event_id         UUID NOT NULL,

    attempt_number          INTEGER NOT NULL,

    processor               VARCHAR(255),

    started_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at            TIMESTAMPTZ,

    status                  VARCHAR(30) NOT NULL,

    error_message           TEXT,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT fk_outbox_event_attempts_tenant
        FOREIGN KEY (tenant_id)
        REFERENCES tenants(id),

    CONSTRAINT fk_outbox_event_attempts_event_tenant
        FOREIGN KEY (tenant_id, outbox_event_id)
        REFERENCES outbox_events(tenant_id, id)
        ON DELETE CASCADE,

    CONSTRAINT uk_outbox_event_attempts_tenant_id
        UNIQUE (tenant_id, id),

    CONSTRAINT uk_outbox_event_attempt_number
        UNIQUE (
            tenant_id,
            outbox_event_id,
            attempt_number
        ),

    CONSTRAINT ck_outbox_event_attempt_number
        CHECK (attempt_number > 0),

    CONSTRAINT ck_outbox_event_attempt_status
        CHECK (
            status IN (
                'STARTED',
                'SUCCESS',
                'FAILED'
            )
        ),

    CONSTRAINT ck_outbox_event_attempt_dates
        CHECK (
            completed_at IS NULL
            OR completed_at >= started_at
        )
);


CREATE INDEX ix_outbox_event_attempts_event
    ON outbox_event_attempts (
        tenant_id,
        outbox_event_id,
        attempt_number DESC
    );


CREATE INDEX ix_outbox_event_attempts_status
    ON outbox_event_attempts (
        tenant_id,
        status,
        started_at DESC
    );